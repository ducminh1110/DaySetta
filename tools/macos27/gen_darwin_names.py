#!/usr/bin/env python3
"""Generate src/darwin/sysnames.inc (BSD syscall and Mach trap names) from xnu sources.

Sources (a Darling xnu snapshot, which is NOT xnu-12377: numbers above its last entry are
reported as unknown by ds-run, never guessed):
  bsd/kern/syscalls.master   lines `NUM<ws>AUE_..<ws>ALL<ws>{ ret name(args) ... }`
  osfmk/kern/syscall_sw.c    lines `/* N */ MACH_TRAP(name, ...`
Usage: gen_darwin_names.py <xnu-root> > src/darwin/sysnames.inc
"""
import re, sys
root = sys.argv[1]
bsd = {}
for line in open(f"{root}/bsd/kern/syscalls.master", errors="replace"):
    m = re.match(r"^(\d+)\s+\S+\s+\S+\s*\{\s*(?:\S+\s+)+?\**(\w+)\s*\(", line)
    if m:
        name = m.group(2)
        if name in ("nosys", "enosys"):
            continue
        bsd.setdefault(int(m.group(1)), name)  # first definition wins (#if branches)
mach = {}
for line in open(f"{root}/osfmk/kern/syscall_sw.c", errors="replace"):
    m = re.match(r"^/\* (\d+) \*/ MACH_TRAP\((\w+),", line)
    if m and m.group(2) != "kern_invalid":
        mach.setdefault(int(m.group(1)), m.group(2))
print("// GENERATED by tools/macos27/gen_darwin_names.py from xnu bsd/kern/syscalls.master and osfmk/kern/syscall_sw.c")
print("// (evidence: SOURCE; names only, numbers are exactly the master-file column)")
print("static const NameEntry kBsdNames[] = {")
for n in sorted(bsd): print(f'    {{{n}, "{bsd[n]}"}},')
print("};")
print("static const NameEntry kMachNames[] = {")
for n in sorted(mach): print(f'    {{{n}, "{mach[n]}"}},')
print("};")
