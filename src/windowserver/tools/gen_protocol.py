#!/usr/bin/env python3
"""Generate the C routine table and Markdown reference from a protocol JSON (see mig_clients.py)."""
import json, os, sys

def main(src, out_dir, docs_path):
    table = json.load(open(src))
    version = os.path.splitext(os.path.basename(src))[0]
    rows = sorted((r for r in table if r['direction'] == 'client->server'), key=lambda r: r['id'])

    with open(os.path.join(out_dir, 'dl_routines.h'), 'w') as h:
        h.write(f'/* Generated by tools/gen_protocol.py from protocol/{version}.json. Do not edit. */\n')
        h.write('#ifndef DL_ROUTINES_H\n#define DL_ROUTINES_H\n\n#include <stdint.h>\n\n')
        h.write('typedef struct dl_routine_info {\n\tint32_t id;\n\tconst char *subsystem;\n\tconst char *name;\n} dl_routine_info;\n\n')
        for r in rows:
            h.write(f'#define DL_MSG_{r["routine"]} {r["id"]}\n')
        h.write(f'\n#define DL_ROUTINE_COUNT {len(rows)}\n')
        h.write('extern const dl_routine_info dl_routines[DL_ROUTINE_COUNT];\n')
        h.write('const dl_routine_info *dl_routine_lookup(int32_t id);\n\n#endif\n')

    with open(os.path.join(out_dir, 'dl_routines.c'), 'w') as c:
        c.write(f'/* Generated by tools/gen_protocol.py from protocol/{version}.json. Do not edit. */\n')
        c.write('#include <stddef.h>\n#include "dl_routines.h"\n\nconst dl_routine_info dl_routines[DL_ROUTINE_COUNT] = {\n')
        for r in rows:
            c.write(f'\t{{ {r["id"]}, "{r["subsystem"]}", "{r["routine"]}" }},\n')
        c.write('};\n\nconst dl_routine_info *dl_routine_lookup(int32_t id)\n{\n')
        c.write('\tsize_t lo = 0, hi = DL_ROUTINE_COUNT;\n\twhile (lo < hi) {\n\t\tsize_t mid = (lo + hi) / 2;\n')
        c.write('\t\tif (dl_routines[mid].id == id)\n\t\t\treturn &dl_routines[mid];\n')
        c.write('\t\tif (dl_routines[mid].id < id)\n\t\t\tlo = mid + 1;\n\t\telse\n\t\t\thi = mid;\n\t}\n\treturn NULL;\n}\n')

    subs = {}
    for r in rows:
        subs.setdefault(r['subsystem'], []).append(r)
    with open(docs_path, 'w') as d:
        d.write(f'# WindowServer protocol reference ({version})\n\n')
        d.write('Generated from the MIG server tables in SkyLight by `tools/mig_scan.py` and `tools/mig_clients.py`. ')
        d.write('Only routine numbers and names are recorded; no Apple code is included.\n\n')
        d.write('| Subsystem | ID range | Routines | Sent directly by a public API |\n|---|---|---|---|\n')
        for s, rs in subs.items():
            d.write(f'| {s} | {rs[0]["id"]}–{rs[-1]["id"]} | {len(rs)} | {sum(1 for r in rs if r["direct_api"])} |\n')
        for s, rs in subs.items():
            d.write(f'\n## {s}\n\n| ID | Routine | Public API that sends it (direct, else indirect) |\n|---|---|---|\n')
            for r in rs:
                names = r['direct_api'] or r['public_api']
                api = ', '.join(f'`{a}`' for a in names[:4]) + (' …' if len(names) > 4 else '')
                if names and not r['direct_api']:
                    api += ' (indirect)'
                d.write(f'| {r["id"]} | `{r["routine"]}` | {api} |\n')
    print(f'{len(rows)} client->server routines in {len(subs)} subsystems')

if __name__ == '__main__':
    main(*sys.argv[1:4])
