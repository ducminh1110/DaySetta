#!/usr/bin/env python3
"""Generate server/src/dl_reply_sizes.c: expected reply size per WindowServer routine, from the 26.6 SkyLight
client code (the receive-buffer size passed to mach_msg right after the msgh_id is stored).

Daylight answers unimplemented routines that have no recorded reply with KERN_SUCCESS and zeroed out-parameters
of that size, so clients keep going.
  reply_sizes.py ~/macos-re/re/SkyLight.dis > server/src/dl_reply_sizes.c
"""
import re, sys

sizes = {}
lines = open(sys.argv[1], errors='replace').read().splitlines()
for i, line in enumerate(lines):
    m = re.search(r'movabsq\s+\$0x([0-9a-f]+)00000000,', line)
    if not m:
        continue
    rid = int(m.group(1), 16)
    if not 29000 <= rid < 36000:
        continue
    rcv = None
    for j in range(i + 1, min(i + 40, len(lines))):
        if 'callq' in lines[j] and rcv is not None:
            break
        m2 = re.search(r'movl\s+\$0x([0-9a-f]+), %ecx', lines[j])
        if m2:
            rcv = int(m2.group(1), 16)
    if rcv and 0x24 <= rcv <= 0x4000:
        sizes.setdefault(rid, set()).add(rcv)
print('/* Generated by tools/trace/reply_sizes.py from SkyLight 26.6 (x86_64). Do not edit. */')
print('#include "dl_reply_sizes.h"\n')
print('const dl_reply_size dl_reply_sizes[] = {')
for rid in sorted(sizes):
    print('\t{ %d, %d },' % (rid, max(sizes[rid])))
print('};')
print('const size_t dl_reply_size_count = sizeof(dl_reply_sizes) / sizeof(dl_reply_sizes[0]);')
print('%d routines' % len(sizes), file=sys.stderr)
