#!/usr/bin/env python3
"""Regenerate include/dl_routines.h, src/dl_routines.c, src/dl_reply_sizes.c and protocol/mig27-status.json for macOS 27.

Inputs: protocol/mig-routines.json (27 SkyLight MIG tables, addresses/ids/max_reply_msg) and
protocol/macos-26.6-x86_64.json (names) plus the 26.6 reply sizes (src/dl_reply_sizes.c as seeded from Daylight, git history).
Rules (nothing is invented):
  - id/subsystem come from the 27 table; names only by id from 26.6 (inferred-from-26.6, same as the 27 JSON).
  - reply size 27 = max_reply_msg + 8 (trailer); a 26.6 client-buffer size is kept only if it equals that
    (confirmed in both versions). Differing ids are CHANGED: no size emitted (no default-success reply), listed in status json.
  - ids absent from 26.6 are ADDED (name Added27_<id>), no size; ids only in 26.6 are REMOVED (dropped from the table).
  usage: gen27.py OLD_SIZES.c   (path of the 26.6 dl_reply_sizes.c)
"""
import json, re, sys, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
old_names = {r['id']: (r['subsystem'], r['routine']) for r in json.load(open(f'{H}/protocol/macos-26.6-x86_64.json')) if r['direction'] == 'client->server'}
m27 = json.load(open(f'{H}/protocol/mig-routines.json'))
old_sizes = {int(a): int(b) for a, b in re.findall(r'\{ (\d+), (\d+) \}', open(sys.argv[1]).read())}
rows, sizes, status = [], [], {'same': 0, 'changed': [], 'added': [], 'removed': [], 'ignored_subsystems': []}
for s in m27['subsystems']:
    if s['name'] == '?':
        status['ignored_subsystems'].append({'start': s['start'], 'end': s['end'], 'descriptor': s['descriptor_vmaddr']})
        continue
    for r in s['routines']:
        i = r['id']; want = r['max_reply_msg'] + 8
        if i not in old_names:
            rows.append((i, s['name'], f'Added27_{i}', 2)); status['added'].append(i); continue
        _, name = old_names[i]
        if i in old_sizes and old_sizes[i] != want:
            rows.append((i, s['name'], name, 1)); status['changed'].append({'id': i, 'name_26_6': name, 'size_26_6': old_sizes[i], 'max_reply_msg_27': r['max_reply_msg']}); continue
        rows.append((i, s['name'], name, 0)); status['same'] += 1
        if i in old_sizes: sizes.append((i, want))
rows.sort()
status['removed'] = sorted(set(old_names) - {r[0] for r in rows})
rows_ids = {r[0] for r in rows}
with open(f'{H}/include/dl_routines.h', 'w') as h:
    h.write('/* Generated by tools/gen27.py from protocol/mig-routines.json (macOS 27). Do not edit. */\n#ifndef DL_ROUTINES_H\n#define DL_ROUTINES_H\n\n#include <stdint.h>\n\n')
    h.write('/* status vs 26.6: 0 same shape, 1 CHANGED (reply size differs; name by id unverified), 2 ADDED in 27 (name unknown) */\n')
    h.write('typedef struct dl_routine_info {\n\tint32_t id;\n\tconst char *subsystem;\n\tconst char *name;\n\tuint8_t status;\n} dl_routine_info;\n\n')
    for i, _, n, st in rows:
        if st != 2: h.write(f'#define DL_MSG_{n} {i}\n')
    h.write(f'\n#define DL_ROUTINE_COUNT {len(rows)}\nextern const dl_routine_info dl_routines[DL_ROUTINE_COUNT];\nconst dl_routine_info *dl_routine_lookup(int32_t id);\n\n#endif\n')
with open(f'{H}/src/dl_routines.c', 'w') as c:
    c.write('/* Generated by tools/gen27.py from protocol/mig-routines.json (macOS 27). Do not edit. */\n#include <stddef.h>\n#include "dl_routines.h"\n\nconst dl_routine_info dl_routines[DL_ROUTINE_COUNT] = {\n')
    for i, sub, n, st in rows: c.write(f'\t{{ {i}, "{sub}", "{n}", {st} }},\n')
    c.write('};\n\nconst dl_routine_info *dl_routine_lookup(int32_t id)\n{\n\tsize_t lo = 0, hi = DL_ROUTINE_COUNT;\n\twhile (lo < hi) {\n\t\tsize_t mid = (lo + hi) / 2;\n\t\tif (dl_routines[mid].id == id)\n\t\t\treturn &dl_routines[mid];\n\t\tif (dl_routines[mid].id < id)\n\t\t\tlo = mid + 1;\n\t\telse\n\t\t\thi = mid;\n\t}\n\treturn NULL;\n}\n')
with open(f'{H}/src/dl_reply_sizes.c', 'w') as c:
    c.write('/* Generated by tools/gen27.py: macOS 27 reply sizes (max_reply_msg + 8) confirmed equal to the 26.6 client buffers. Do not edit. */\n#include "dl_reply_sizes.h"\n\nconst dl_reply_size dl_reply_sizes[] = {\n')
    for i, z in sorted(sizes): c.write(f'\t{{ {i}, {z} }},\n')
    c.write('};\nconst size_t dl_reply_size_count = sizeof(dl_reply_sizes) / sizeof(dl_reply_sizes[0]);\n')
json.dump(status, open(f'{H}/protocol/mig27-status.json', 'w'), indent=1)
print(len(rows), 'routines;', status['same'], 'same;', len(status['changed']), 'changed;', len(status['added']), 'added;', len(status['removed']), 'removed;', len(sizes), 'sizes')
